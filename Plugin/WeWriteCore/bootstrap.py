# Stdin / stdout helpers (VCP synchronous plugin protocol)
# ---------------------------------------------------------------------------

def read_args() -> dict[str, Any]:
    """Read the JSON arg object that VCP delivers on stdin.

    Tolerates an optional UTF-8 BOM (some shells / VCP test harnesses
    insert one) and leading/trailing whitespace.
    """
    raw = sys.stdin.read()
    if not raw:
        return {}
    if raw.startswith("\ufeff"):
        raw = raw.lstrip("\ufeff")
    raw = raw.strip()
    if not raw:
        return {}
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON on stdin: {e}") from e
    if not isinstance(data, dict):
        raise ValueError(f"Expected JSON object on stdin, got {type(data).__name__}")
    return data


def success(result: Any) -> None:
    """Emit a VCP success envelope to stdout and exit."""
    sys.stdout.write(json.dumps({"status": "success", "result": result}, ensure_ascii=False))
    sys.stdout.flush()
    sys.exit(0)


def failure(error: str, *, code: str | None = None, extra: dict | None = None) -> None:
    """Emit a VCP error envelope to stdout and exit."""
    payload: dict[str, Any] = {"status": "error", "error": str(error)}
    if code:
        payload["code"] = code
    if extra:
        payload.update(extra)
    sys.stdout.write(json.dumps(payload, ensure_ascii=False))
    sys.stdout.flush()
    sys.exit(1)


def pick(args: dict[str, Any], *aliases: str, default: Any = None) -> Any:
    """Look up an argument by any of the given aliases (case-insensitive)."""
    if not args:
        return default
    lowered = {str(k).lower(): v for k, v in args.items()}
    for alias in aliases:
        v = args.get(alias)
        if v not in (None, ""):
            return v
        v = lowered.get(alias.lower())
        if v not in (None, ""):
            return v
    return default


