def render_config_yaml() -> Path:
    """Render `wewrite/config.yaml` from VCP env vars.

    Only writes when at least one of the supported env vars is set, OR when
    no config.yaml currently exists (in which case an empty stub is written
    so wewrite's "skip_publish"/"skip_image_gen" auto-degrade kicks in).
    """
    path = SKILL_DIR / "config.yaml"

    appid = _env("WECHAT_APPID")
    secret = _env("WECHAT_SECRET")
    author = _env("WECHAT_AUTHOR") or _env("WEWRITE_AUTHOR")
    theme = _env("WEWRITE_DEFAULT_THEME", "professional-clean")

    lines: list[str] = ["# Auto-generated by Plugin/WeWriteCore/bootstrap.py", ""]
    if appid or secret or author:
        lines.append("wechat:")
        lines.append(f"  appid: \"{appid or ''}\"")
        lines.append(f"  secret: \"{secret or ''}\"")
        if author:
            lines.append(f"  author: \"{author}\"")
        lines.append("")

    lines.append(f"theme: \"{theme}\"")
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def render_style_yaml() -> Path:
    """Render `wewrite/style.yaml` from VCP env vars when set.

    This is needed by the Agent-facing SKILL.md flow (Step 1.3). For pure
    Markdown→HTML and publish use-cases the file is not consulted by
    toolkit code, but we still write a sensible stub so that downstream
    scripts (fetch_hotspots, extract_exemplar, ...) can run later.
    """
    path = SKILL_DIR / "style.yaml"

    def _yaml_str(v: str) -> str:
        return json.dumps(v, ensure_ascii=False)

    def _yaml_list(items: list[str]) -> str:
        if not items:
            return "[]"
        return "[" + ", ".join(_yaml_str(i) for i in items) + "]"

    name = _env("WEWRITE_NAME", "VCP公众号")
    industry = _env("WEWRITE_INDUSTRY", "科技/互联网")
    audience = _env("WEWRITE_TARGET_AUDIENCE", "")
    topics = _split_csv(_env("WEWRITE_TOPICS"))
    tone = _env("WEWRITE_TONE", "专业但不学术，有观点但不偏激")
    voice = _env("WEWRITE_VOICE", "第一人称，像一个懂行的朋友在分享见解")
    word_count = _env("WEWRITE_WORD_COUNT", "1500-2500")
    content_style = _env("WEWRITE_CONTENT_STYLE", "干货")
    persona = _env("WEWRITE_WRITING_PERSONA", "midnight-friend")
    theme = _env("WEWRITE_DEFAULT_THEME", "professional-clean")
    author = _env("WEWRITE_AUTHOR", "")
    cover_style = _env("WEWRITE_COVER_STYLE", "简洁封面，主体明确")
    blacklist_words = _split_csv(_env("WEWRITE_BLACKLIST_WORDS"))
    blacklist_topics = _split_csv(_env("WEWRITE_BLACKLIST_TOPICS"))
    reference_accounts = _split_csv(_env("WEWRITE_REFERENCE_ACCOUNTS"))

    lines: list[str] = [
        "# Auto-generated by Plugin/WeWriteCore/bootstrap.py",
        f"name: {_yaml_str(name)}",
        f"industry: {_yaml_str(industry)}",
    ]
    if audience:
        lines.append(f"target_audience: {_yaml_str(audience)}")

    lines.append("topics:")
    for t in (topics or ["AI/人工智能", "效率工具"]):
        lines.append(f"  - {_yaml_str(t)}")

    lines += [
        f"tone: {_yaml_str(tone)}",
        f"voice: {_yaml_str(voice)}",
        f"word_count: {_yaml_str(word_count)}",
        f"content_style: {_yaml_str(content_style)}",
        f"writing_persona: {_yaml_str(persona)}",
        "blacklist:",
        f"  words: {_yaml_list(blacklist_words)}",
        f"  topics: {_yaml_list(blacklist_topics)}",
        f"reference_accounts: {_yaml_list(reference_accounts)}",
        f"theme: {_yaml_str(theme)}",
        f"cover_style: {_yaml_str(cover_style)}",
    ]
    if author:
        lines.append(f"author: {_yaml_str(author)}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def ensure_runtime() -> dict[str, Path]:
    """Ensure wewrite is ready to be invoked. Returns key paths."""
    if not SKILL_DIR.exists():
        raise RuntimeError(
            f"Embedded wewrite source missing at {SKILL_DIR}. "
            "Re-run the WeWriteCore installation."
        )
    config_path = render_config_yaml()
    style_path = render_style_yaml()

    for sub in ("output", "lessons", "corpus"):
        (SKILL_DIR / sub).mkdir(parents=True, exist_ok=True)

    return {
        "skill_dir": SKILL_DIR,
        "toolkit_dir": TOOLKIT_DIR,
        "scripts_dir": SCRIPTS_DIR,
        "config": config_path,
        "style": style_path,
    }


