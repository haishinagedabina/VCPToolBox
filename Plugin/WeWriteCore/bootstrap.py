"""
WeWriteCore bootstrap utility.

Bridges VCP plugin environment (env vars + stdin JSON args) to the
unmodified `wewrite/` source tree shipped in this directory.

Responsibilities:
  1. Locate the embedded `wewrite/` skill root.
  2. Render `wewrite/config.yaml` and `wewrite/style.yaml` from VCP env
     vars, so that wewrite's CLI and scripts behave as if a user had
     run the upstream onboarding flow.
  3. Provide helpers for spawning wewrite scripts and for resolving
     remote `file://` URLs via VCP hyper-stack-trace.

This module is imported by every WeWrite* plugin (WeWriteRender,
WeWritePublish, WeWriteThemes, ...). It is NOT a standalone plugin
itself (no plugin-manifest.json).

The embedded wewrite source is treated as read-only: bootstrap only
writes the generated *.yaml configs into the wewrite root. Everything
else is left untouched so `git pull` upstream stays trivial.
"""

from __future__ import annotations

import base64
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Iterable
from urllib.parse import urlparse, unquote
from urllib.request import urlopen


CORE_DIR: Path = Path(__file__).resolve().parent
SKILL_DIR: Path = CORE_DIR / "wewrite"
TOOLKIT_DIR: Path = SKILL_DIR / "toolkit"
SCRIPTS_DIR: Path = SKILL_DIR / "scripts"


# Force UTF-8 on stdio. The VCP synchronous-plugin protocol speaks JSON with
# Chinese punctuation and the HTML body emitted by wewrite contains bullets
# (U+2022) and many CJK chars that the default Windows console codec (cp936)
# cannot encode. We must reconfigure before any read/write.
for _stream_name in ("stdin", "stdout", "stderr"):
    _stream = getattr(sys, _stream_name, None)
    if _stream is not None and hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


# Strip inherited HTTP/HTTPS proxy env vars before anything else imports
# `requests` / `urllib`. Rationale:
#   - WeChat Open Platform requires API calls to come from a whitelisted public
#     IP. A LAN proxy (e.g. 127.0.0.1:8800) is either unreachable from this
#     child process or has an outbound IP that is NOT in the whitelist, which
#     causes 40164 errors or socket failures.
#   - VCP's server.js inherits whatever proxy env vars were set in the shell
#     that launched it. On Windows, Cursor/IDE terminals frequently carry stale
#     or malformed (e.g. markdown-wrapped) proxy values that propagate into
#     every spawned plugin subprocess.
#   - Allow an explicit opt-in via WEWRITE_ALLOW_PROXY=1 for advanced users who
#     have a whitelisted upstream proxy.
if os.environ.get("WEWRITE_ALLOW_PROXY", "").lower() not in ("1", "true", "yes"):
    _proxy_vars = (
        "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
        "http_proxy", "https_proxy", "all_proxy",
    )
    _stripped: list[str] = []
    for _v in _proxy_vars:
        if _v in os.environ:
            _stripped.append(f"{_v}={os.environ[_v]!r}")
            del os.environ[_v]
    os.environ["NO_PROXY"] = "*"
    os.environ["no_proxy"] = "*"
    if _stripped and os.environ.get("DebugMode", "").lower() in ("true", "1"):
        print(f"[WeWriteCore] stripped inherited proxy env: {_stripped}",
              file=sys.stderr, flush=True)


def _split_csv(raw: str | None) -> list[str]:
    if not raw:
        return []
    parts = re.split(r"[,，;；\n]+", raw)
    return [p.strip() for p in parts if p.strip()]


def _env(key: str, default: str | None = None) -> str | None:
    val = os.environ.get(key)
    if val is None or val == "":
        return default
    return val


def _bool_env(key: str, default: bool = False) -> bool:
    val = os.environ.get(key)
    if val is None:
        return default
    return val.strip().lower() in ("1", "true", "yes", "on", "y")


