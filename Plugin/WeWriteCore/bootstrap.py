def materialize_markdown(value: str, *, prefix: str = "wewrite-") -> Path:
    """Turn a string OR a path into a real file on disk.

    Accepts:
      - Raw markdown content (heuristic: contains newlines, '#', or no path-like chars).
      - An absolute or relative filesystem path.
      - A `file://` URL.
    """
    if not value:
        raise ValueError("Empty markdown input")

    # file:// URL → local path
    if value.startswith("file://"):
        parsed = urlparse(value)
        local = Path(unquote(parsed.path.lstrip("/")) if os.name == "nt" else unquote(parsed.path))
        if local.exists() and local.is_file():
            return local
        raise FileNotFoundError(value)

    candidate = Path(value)
    looks_like_path = (
        len(value) < 1024
        and "\n" not in value
        and ("/" in value or "\\" in value or value.lower().endswith((".md", ".markdown", ".txt")))
    )
    if looks_like_path and candidate.exists() and candidate.is_file():
        return candidate

    # Treat as raw markdown content → write to temp file under wewrite/output
    out_dir = SKILL_DIR / "output"
    out_dir.mkdir(parents=True, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix=prefix, suffix=".md", dir=str(out_dir))
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(value)
    return Path(tmp_path)


