# Cover-image input (supports VCP hyper-stack-trace)
# ---------------------------------------------------------------------------

def _has_pw_segment(parsed_path: str) -> bool:
    return any(part.startswith("pw=") for part in parsed_path.split("/") if part)


def is_local_image_server_url(value: str) -> bool:
    """Return true for VCP image-server URLs that can be resolved locally."""
    parsed = urlparse(value)
    if parsed.scheme not in ("http", "https"):
        return False

    parts = [part for part in parsed.path.split("/") if part]
    if "images" not in parts:
        return False

    host = (parsed.hostname or "").lower()
    local_hosts = {"localhost", "127.0.0.1", "::1"}
    return host in local_hosts or _has_pw_segment(parsed.path)


def local_image_server_path(value: str) -> Path | None:
    """Map a VCP `/images/...` URL back to PROJECT_BASE_PATH/image/..."""
    if not is_local_image_server_url(value):
        return None

    project_base = os.environ.get("PROJECT_BASE_PATH", "").strip()
    if not project_base:
        return None

    parsed = urlparse(value)
    parts = [unquote(part) for part in parsed.path.split("/") if part]
    try:
        images_idx = parts.index("images")
    except ValueError:
        return None

    relative_parts = parts[images_idx + 1:]
    if not relative_parts:
        return None

    candidate = Path(project_base) / "image" / Path(*relative_parts)
    if candidate.exists() and candidate.is_file():
        return candidate
    return None


def materialize_image(value: str, *, param_name: str) -> Path:
    """Resolve an image URL/path/data URI to a real local file.

    Supports:
      - Local path (absolute or relative)
      - file:// URL (raises FILE_NOT_FOUND_LOCALLY for VCP hyper-stack-trace
        if the file does not exist on this node)
      - http(s):// URL (downloaded)
      - data:image/...;base64,... URI

    Raises a structured exception that the plugin entry should catch and
    forward to VCP via `emit_file_not_found`.
    """
    if not value:
        raise ValueError(f"{param_name}: empty value")

    # data URI
    m = re.match(r"^data:(image/[^;]+);base64,(.*)$", value, re.IGNORECASE | re.DOTALL)
    if m:
        ext = (m.group(1).split("/", 1)[1] or "png").split("+", 1)[0]
        raw = base64.b64decode(m.group(2))
        tmp = Path(tempfile.mkstemp(prefix="wewrite-img-", suffix=f".{ext}", dir=str(SKILL_DIR / "output"))[1])
        tmp.write_bytes(raw)
        return tmp

    # file:// URL
    if value.startswith("file://"):
        parsed = urlparse(value)
        raw_path = unquote(parsed.path)
        if os.name == "nt" and raw_path.startswith("/") and re.match(r"^/[A-Za-z]:", raw_path):
            raw_path = raw_path[1:]
        local = Path(raw_path)
        if local.exists() and local.is_file():
            return local
        err = FileNotFoundError(f"{param_name}: local file not found, requires remote fetch")
        err.code = "FILE_NOT_FOUND_LOCALLY"  # type: ignore[attr-defined]
        err.fileUrl = value  # type: ignore[attr-defined]
        err.failedParameter = param_name  # type: ignore[attr-defined]
        raise err

    # http(s)://
    if value.startswith(("http://", "https://")):
        local_server_path = local_image_server_path(value)
        if local_server_path is not None:
            return local_server_path
        if is_local_image_server_url(value):
            raise FileNotFoundError(f"{param_name}: file not found: {value}")

        with urlopen(value, timeout=60) as resp:
            data = resp.read()
            ct = resp.headers.get_content_type() or "image/png"
            ext = ct.split("/", 1)[1].split(";", 1)[0] or "png"
        tmp = Path(tempfile.mkstemp(prefix="wewrite-img-", suffix=f".{ext}", dir=str(SKILL_DIR / "output"))[1])
        tmp.write_bytes(data)
        return tmp

    # Plain path
    local = Path(value)
    if local.exists() and local.is_file():
        return local

    project_base = os.environ.get("PROJECT_BASE_PATH", "").strip()
    if project_base and not local.is_absolute():
        project_candidate = Path(project_base) / local
        if project_candidate.exists() and project_candidate.is_file():
            return project_candidate

    raise FileNotFoundError(f"{param_name}: file not found: {value}")


def emit_file_not_found(err: BaseException) -> None:
    """Emit the VCP `FILE_NOT_FOUND_LOCALLY` envelope and exit."""
    payload = {
        "status": "error",
        "code": "FILE_NOT_FOUND_LOCALLY",
        "error": str(err),
        "fileUrl": getattr(err, "fileUrl", ""),
    }
    failed_param = getattr(err, "failedParameter", None)
    if failed_param:
        payload["failedParameter"] = failed_param
    sys.stdout.write(json.dumps(payload, ensure_ascii=False))
    sys.stdout.flush()
    sys.exit(1)


