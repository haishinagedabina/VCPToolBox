def run_python(script: Path, args: Iterable[str], *, cwd: Path | None = None,
               timeout: int = 600) -> subprocess.CompletedProcess:
    """Run a wewrite python script with sane defaults."""
    cmd = [sys.executable, str(script), *args]
    env = os.environ.copy()
    py_path = os.pathsep.join(
        p for p in (str(TOOLKIT_DIR), str(SCRIPTS_DIR), env.get("PYTHONPATH", "")) if p
    )
    env["PYTHONPATH"] = py_path
    env.setdefault("PYTHONIOENCODING", "utf-8")
    return subprocess.run(
        cmd,
        cwd=str(cwd) if cwd else str(SKILL_DIR),
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=timeout,
    )


def inject_toolkit_path() -> None:
    """Add wewrite toolkit/scripts dirs to sys.path so `import converter`,
    `import theme`, etc. work directly inside the current process."""
    for d in (TOOLKIT_DIR, SCRIPTS_DIR):
        s = str(d)
        if s not in sys.path:
            sys.path.insert(0, s)


